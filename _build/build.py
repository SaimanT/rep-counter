def links_html(pages, root, skip=None):
    items = "\n".join(
        f'    <li><a href="{root}{p["slug"]}/">{escape(p["h1"])}</a></li>'
        for p in pages if p["slug"] and p["slug"] != skip
    )
    return f'  <ul class="links">\n{items}\n  </ul>'


